let currentPayload = null;

function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

function decodePayload(code) {
  const json = decodeURIComponent(escape(atob(code)));
  return JSON.parse(json);
}

function getPayloadFromHash() {
  const hash = window.location.hash || "";
  const match = hash.match(/payload=([^&]+)/);
  return match ? match[1] : "";
}

function clearNode(node) {
  while (node.firstChild) node.removeChild(node.firstChild);
}

function toggleVisible(id, visible) {
  document.getElementById(id).classList.toggle("hidden", !visible);
}

function renderAll(payload) {
  currentPayload = payload;

  toggleVisible("candidateInfo", true);
  toggleVisible("quizSection", true);
  toggleVisible("situationsSection", true);
  toggleVisible("rulesSection", true);

  document.getElementById("infoName").textContent = payload.candidateName || "-";
  document.getElementById("infoDiscord").textContent = payload.discordName || "-";
  document.getElementById("infoDate").textContent = payload.submittedAt ? new Date(payload.submittedAt).toLocaleString("ro-RO") : "-";

  renderQuiz(payload);
  renderOpenSection("situationResults", payload.situations || [], TEST.situations, BAREM.situations, "situation");
  renderOpenSection("rulesResults", payload.rules || [], TEST.rules, BAREM.rules, "rule");
  updateFinalScore();
}

function renderQuiz(payload) {
  const root = document.getElementById("quizResults");
  clearNode(root);
  let score = 0;

  TEST.quiz.forEach((item, index) => {
    const selected = payload.quiz?.[index]?.selected || "";
    const correct = BAREM.quizCorrect[index];
    const isCorrect = selected === correct;
    if (isCorrect) score += item.points;

    const box = el("article", "question");
    const top = el("div", "question-top");
    top.append(el("h3", "", `${index + 1}. ${item.question}`), el("span", "points", `${item.points}p`));
    box.appendChild(top);

    const options = el("div", "options");
    Object.entries(item.options).forEach(([key, value]) => {
      const label = el("div", "option");
      if (key === correct) label.classList.add("correct");
      if (key === selected && key !== correct) label.classList.add("wrong");
      label.textContent = `${key}. ${value}`;
      options.appendChild(label);
    });

    box.appendChild(options);
    box.appendChild(el("p", "", `Ales de candidat: ${selected || "fără răspuns"} | Corect: ${correct}`));
    root.appendChild(box);
  });

  document.getElementById("quizScore").textContent = `${score} / 30`;
  document.getElementById("quizScore").dataset.score = String(score);
}

function renderOpenSection(rootId, answers, questionList, baremList, type) {
  const root = document.getElementById(rootId);
  clearNode(root);

  questionList.forEach((item, index) => {
    const answer = answers[index]?.answer || "";
    const box = el("article", "question");
    const top = el("div", "question-top");
    top.append(el("h3", "", `${index + 1}. ${item.title}`), el("span", "points", `${item.points}p`));
    box.appendChild(top);

    if (item.scenario) box.appendChild(el("p", "scenario", `Situație: ${item.scenario}`));
    if (item.question) box.appendChild(el("p", "", `Întrebare: ${item.question}`));

    const answerTitle = el("p", "", "Răspuns candidat:");
    const answerArea = el("div", "answer-area", answer || "Fără răspuns.");
    box.append(answerTitle, answerArea);

    const controls = el("div", "grid two");
    controls.style.marginTop = "14px";

    const pointsLabel = document.createElement("label");
    pointsLabel.textContent = `Punctaj acordat / ${item.points}`;
    const input = document.createElement("input");
    input.type = "number";
    input.min = "0";
    input.max = String(item.points);
    input.step = "0.5";
    input.value = "0";
    input.className = "manual-points";
    input.dataset.max = String(item.points);
    input.dataset.type = type;
    input.addEventListener("input", updateFinalScore);
    pointsLabel.appendChild(input);

    const commentLabel = document.createElement("label");
    commentLabel.textContent = "Observații evaluator";
    const comment = document.createElement("textarea");
    comment.placeholder = "Ex: răspuns complet / incomplet / lipsesc pași procedurali...";
    comment.style.minHeight = "70px";
    commentLabel.appendChild(comment);

    controls.append(pointsLabel, commentLabel);
    box.appendChild(controls);

    const actions = el("div", "actions no-print");
    const btn = document.createElement("button");
    btn.type = "button";
    btn.textContent = "Arată/ascunde barem";
    const barem = el("div", "barem");
    const ul = document.createElement("ul");
    baremList[index].forEach(line => ul.appendChild(el("li", "", line)));
    barem.append(el("strong", "", "Barem orientativ:"), ul);
    btn.addEventListener("click", () => barem.classList.toggle("show"));
    actions.appendChild(btn);

    box.append(actions, barem);
    root.appendChild(box);
  });
}

function updateFinalScore() {
  const quiz = parseFloat(document.getElementById("quizScore")?.dataset.score || "0");
  let manual = 0;

  document.querySelectorAll(".manual-points").forEach(input => {
    const max = parseFloat(input.dataset.max || "0");
    let value = parseFloat(input.value || "0");
    if (Number.isNaN(value)) value = 0;
    value = Math.max(0, Math.min(max, value));
    if (String(value) !== input.value && document.activeElement !== input) input.value = String(value);
    manual += value;
  });

  const total = Math.round((quiz + manual) * 10) / 10;
  document.getElementById("finalScore").textContent = `${total} / 100`;
}

function loadFromCode(code) {
  try {
    const payload = decodePayload(code.trim());
    if (!payload || payload.version !== "penitenciar-v2") {
      throw new Error("Versiune invalidă.");
    }
    renderAll(payload);
    document.getElementById("loadStatus").textContent = "Răspunsurile au fost încărcate.";
  } catch (error) {
    document.getElementById("loadStatus").textContent = "Cod invalid sau incomplet. Verifică dacă ai copiat tot codul.";
  }
}

document.addEventListener("DOMContentLoaded", () => {
  const code = getPayloadFromHash();
  if (code) {
    document.getElementById("payloadInput").value = code;
    loadFromCode(code);
  }

  document.getElementById("loadBtn").addEventListener("click", () => {
    loadFromCode(document.getElementById("payloadInput").value);
  });

  document.getElementById("printBtn").addEventListener("click", () => window.print());
});
